"""Resource table for the code generator: what the pinned schema cannot express.

Every result model names its response schema, its docstrings, and the field
rules the schema gets wrong or leaves out. Every endpoint names its kind, its
path, its client method, and the docstrings of that method. The generator
derives everything else from the pinned OpenAPI document.
"""

from collections.abc import Mapping
from dataclasses import dataclass, field
from typing import Literal

type EndpointKind = Literal[
    "collection", "item", "linked", "create", "linked_create", "update", "delete"
]


@dataclass(frozen=True, slots=True)
class ModelSpec:
    """One result model and the field rules that override its schema.

    expand maps a linked field to the model it parses into when expanded.
    datetimes lists string fields that carry a timestamp without saying so.
    coerced lists string fields the API sometimes sends as a number.
    codes lists generated comma separated fields that parse into a tuple.
    nullable lists fields the schema marks required that arrive empty.
    """

    name: str
    schema: str
    doc: str
    nouns: tuple[str, str]
    expand: Mapping[str, str] = field(default_factory=dict)
    datetimes: tuple[str, ...] = ()
    coerced: tuple[str, ...] = ()
    codes: tuple[str, ...] = ()
    nullable: tuple[str, ...] = ()


