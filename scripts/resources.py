@dataclass(frozen=True, slots=True)
class EndpointSpec:
    """One endpoint row and the client method that calls it.

    path uses the schema form, with {id} for the item or parent id. method is
    the client method name without its async_ and verb prefix. param names the
    id argument of that method. docs holds one docstring per client method:
    the list and iter pair for collections, one for every other kind.
    """

    const: str
    kind: EndpointKind
    path: str
    method: str
    docs: tuple[str, ...]
    param: str | None = None


CLIENT_DOC = """Asynchronous client for the Rentman API.

    The client covers every read and write path of the pinned document.
    Collections get a list method for one page and an iter method that
    follows the cursor. Every request holds one of ``max_concurrent`` slots
    and waits for its send turn at the documented rate, unless
    ``requests_per_second=None`` disables the send rate."""

